#!/usr/bin/env node
// Import the Origin Design System icon library (Figma wFRKiKskxZ4vjIHbDVvngJ · 6170:153, "M-Icon/System-Icon/*").
//   npm run icons:import -- <folder of exported SVGs>      e.g. ~/Downloads/origin-icons/M-Icon/System-Icon
//   npm run icons:import                                  regenerate the registry + docs from what is already imported
// 1. Copies every SVG into src/assets/icons/origin/<name>.svg with a clean kebab-case name (Figma typos fixed,
//    Figma's duplicate-name exports `<name>-1` become `<name>-v2`). SVG contents are copied untouched.
// 2. Generates src/components/Icon/originIcons.ts — the typed name list, outline/filled pairs, multicolour flags.
// 3. Generates .claude/skills/noon-ui/references/icons.md — the catalogue the skills use to pick icons.
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dest = join(root, 'src/assets/icons/origin');
const src = process.argv[2]?.replace(/^~(?=\/)/, process.env.HOME);

/** Figma layer names with typos or stray spaces → kit names. */
const renames = {
  'vetricle-three-dot-menu': 'vertical-three-dot-menu',
  'cart-exclaimation': 'cart-exclamation',
  'star-hlf-filled': 'star-half-filled',
  'star- filled-square': 'star-filled-square',
  'noon-icon-wallet': 'noon-wallet-icon',
};
const clean = (raw) => {
  let n = raw.trim().replace(/\s+/g, '-').toLowerCase();
  n = renames[raw] ?? renames[n] ?? n;
  return n.replace(/-1$/, '-v2'); // Figma exports a second layer with the same name as `<name>-1`
};

mkdirSync(dest, { recursive: true });
if (src) {
  if (!existsSync(src)) {
    console.error(`✗ ${src} does not exist`);
    process.exit(1);
  }
  let n = 0;
  for (const f of readdirSync(src)) {
    if (!f.endsWith('.svg')) continue;
    copyFileSync(join(src, f), join(dest, `${clean(basename(f, '.svg'))}.svg`));
    n++;
  }
  console.log(`✓ copied ${n} icons from ${src}`);
}

// ── Registry
const names = readdirSync(dest).filter((f) => f.endsWith('.svg')).map((f) => basename(f, '.svg')).sort();
const set = new Set(names);
const multicolor = names.filter((n) => new Set(readFileSync(join(dest, `${n}.svg`), 'utf8').match(/(?:fill|stroke)="(?!none)[^"]+"/g)).size > 1);
const outline = names.filter((n) => !n.endsWith('-filled') && !/-filled-v\d+$/.test(n));
const pairs = outline.filter((n) => set.has(`${n.replace(/-v(\d+)$/, '')}-filled${n.match(/-v\d+$/)?.[0] ?? ''}`));

writeFileSync(
  join(root, 'src/components/Icon/originIcons.ts'),
  `// GENERATED by scripts/import-origin-icons.mjs — do not edit. Run \`npm run icons:import\` after changing src/assets/icons/origin.
// Origin Design System icons (Figma wFRKiKskxZ4vjIHbDVvngJ · 6170:153): ${names.length} icons, 24×24, single colour unless listed in originMulticolor.

export const originIconNames = [
${names.map((n) => `  '${n}',`).join('\n')}
] as const;

export type OriginIconName = (typeof originIconNames)[number];

/** Icons with more than one colour (white cut-outs): drawn as images, not tinted. */
export const originMulticolor: ReadonlySet<OriginIconName> = new Set<OriginIconName>([${multicolor.map((n) => `'${n}'`).join(', ')}]);
`,
);

// ── Catalogue for the skills
const families = [
  ['Arrows, carets and chevrons', /^(curved-arrow|arrow|caret|chevron|trend|direction|sign-in|sign-out|upload|download|refresh|sort)/],
  ['Actions and controls', /^(plus|minus|cross|edit|bin|copy|link|search|scan|qr-code|crosshair|preferences|horizontal-three|vertical-three|lock|unlock|power|infinity|language|world|country)/],
  ['Status and feedback', /^(check|info|warning|question|help|verified|notification|thumbs|star|medal|one-circle|flame|thunder|flash|hourglass|clock|live)/],
  ['Commerce: cart, bags, deals and payments', /^(cart|bag|shop|discount|coupon|gift|payment|currency|noon-cash|noon-wallet|invoice|combo|new-arrivals|partners|school-bag|briefcase)/],
  ['Delivery, orders and returns', /^(delivery|truck|order|return|rewind|locker|installation|location|pin|home|door|noon-shield|star-shield|calendar|measurement)/],
  ['People, communication and media', /^(user|contact|male|female|message|info-message|call|handset|mic|volume|video|play|pause|forward|previous|camera|gallery|mobile|graduation)/],
  ['Categories and misc', /./],
];
const grouped = new Map(families.map(([title]) => [title, []]));
for (const n of outline) grouped.get(families.find(([, re]) => re.test(n))[0]).push(n);
const filledOnly = names.filter((n) => (n.endsWith('-filled') || /-filled-v\d+$/.test(n)) && !set.has(n.replace(/-filled(-v\d+)?$/, '$1')));
for (const n of filledOnly) grouped.get(families.find(([, re]) => re.test(n))[0]).push(n);

const row = (n) => {
  const filled = `${n.replace(/-v(\d+)$/, '')}-filled${n.match(/-v\d+$/)?.[0] ?? ''}`;
  return `| \`${n}\` | ${set.has(filled) && filled !== n ? `\`${filled}\`` : '—'} |`;
};
writeFileSync(
  join(root, '.claude/skills/noon-ui/references/icons.md'),
  `# Icons (Origin Design System)

<!-- GENERATED by scripts/import-origin-icons.mjs — do not edit by hand; run \`npm run icons:import\`. -->

The noon icon library from the **Origin Design System** Figma (\`wFRKiKskxZ4vjIHbDVvngJ\` · \`6170:153\`, layers \`M-Icon/System-Icon/<name>\`): **${names.length} icons**, 24×24, drawn in \`#1D2539\` (\`textPrimary\`). Files live in \`src/assets/icons/origin/<name>.svg\`; names are the Figma layer names in kebab-case (typos fixed: ${Object.entries(renames).map(([a, b]) => `\`${a}\` → \`${b}\``).join(', ')}; a second Figma layer with the same name is \`<name>-v2\`).

## Using an icon

\`\`\`tsx
import { OriginIcon } from '../../components';

<OriginIcon name="cart-plus" />                                   // 24, textPrimary
<OriginIcon name="heart" filled color={ref.color('wishlist')} />  // → heart-filled, tinted with a token
<OriginIcon name="chevron-right" size={16} color="var(--nk-color-text-secondary)" />
\`\`\`

- \`name\` is typed (\`OriginIconName\` from \`src/components/Icon/originIcons.ts\`), so a wrong name fails \`npm run typecheck\`.
- \`filled\` picks \`<name>-filled\` when the pair exists (outline for default / unselected, filled for selected / active, as noon does).
- \`color\` takes a token (\`ref.color(...)\`, \`var(--nk-*)\`); icons are tinted through a CSS mask, so never recolour by editing the SVG. Multicolour icons (${multicolor.map((n) => `\`${n}\``).join(', ') || 'none'}) render as images and ignore \`color\`.
- Default size 24; the library is drawn on a 24 grid, so prefer 24 / 20 / 16.
- Prefer these over lucide (\`Icon\`) and over one-off webps when a design uses noon's system icons; keep \`Icon\` for existing flows. A Figma icon called \`M-Icon/System-Icon/<name>\` maps 1:1 to \`<OriginIcon name="<name>" />\`.
- New icons: export from Figma, then \`npm run icons:import -- <folder>\`; it copies, renames, regenerates the typed list and this file.

## Catalogue

${names.length} icons, ${pairs.length} outline / filled pairs. Each row: outline (default) · filled (selected).

${[...grouped]
  .filter(([, list]) => list.length)
  .map(([title, list]) => `### ${title}\n\n| icon | filled |\n|---|---|\n${list.map(row).join('\n')}`)
  .join('\n\n')}
`,
);
console.log(`✓ ${names.length} icons · ${pairs.length} pairs · ${multicolor.length} multicolour → src/components/Icon/originIcons.ts, .claude/skills/noon-ui/references/icons.md`);
